"""Self-hosted fonts for the website (no request to Google at runtime).

Run once when the families or weights change (needs fontTools and brotli):
    python3 scripts/build-fonts.py
It downloads the woff2 files from Google Fonts (OFL licensed), keeps the Arabic and Latin
subsets only, trims the Arabic files to the basic Arabic block, writes them to
src/assets/fonts/ and writes src/fonts.css, with size-adjusted local fallbacks so the swap
from the fallback to the web font doesn't move the layout.
"""
import re
import urllib.request
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

HERE = Path(__file__).resolve().parent.parent
OUT = HERE / "src" / "assets" / "fonts"
CSS = HERE / "src" / "fonts.css"
GOOGLE = (
    "https://fonts.googleapis.com/css2?family=Cormorant+Garamond:ital,wght@0,400;0,600;0,700;1,400"
    "&family=IBM+Plex+Sans+Arabic:wght@400;500;600;700&family=Manrope:wght@400..700"
    "&family=Noto+Naskh+Arabic:wght@400;600;700&display=swap"
)
UA = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36"
ARABIC = "U+0600-06FF,U+200C-200F,U+2010-2011,U+204F,U+25CC,U+FDFC-FDFD"
# Metric-compatible stand-ins for the fallbacks the browsers have: Arial and Times New Roman.
LIBERATION = Path("/usr/share/fonts/truetype/liberation")
FALLBACK = {"sans": ("Arial", LIBERATION / "LiberationSans-Regular.ttf"),
            "serif": ("Times New Roman", LIBERATION / "LiberationSerif-Regular.ttf")}
KIND = {"Manrope": "sans", "IBM Plex Sans Arabic": "sans", "Cormorant Garamond": "serif", "Noto Naskh Arabic": "serif"}
# Letter frequencies (English text) for an average character width, as capsize does.
FREQ = "etaoinshrdlcumwfgypbvkjxqz"
ARABIC_FAMILIES = {"IBM Plex Sans Arabic", "Noto Naskh Arabic"}


def avg_width(font: TTFont) -> float:
    cmap, hmtx = font.getBestCmap(), font["hmtx"]
    weights = [(c, 26 - i) for i, c in enumerate(FREQ)] + [(" ", 30)]
    total = sum(w for _, w in weights)
    return sum(hmtx[cmap[ord(c)]][0] * w for c, w in weights if ord(c) in cmap) / total / font["head"].unitsPerEm


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.woff2"):
        old.unlink()
    css = urllib.request.urlopen(urllib.request.Request(GOOGLE, headers={"User-Agent": UA})).read().decode()
    faces, seen = [], {}
    for sub, body in re.findall(r"/\* ([a-z-]+) \*/\s*@font-face \{(.*?)\}", css, re.S):
        if sub not in ("arabic", "latin"):
            continue
        fam = re.search(r"font-family: '([^']+)'", body).group(1)
        # Latin in Arabic text uses the Latin families (Manrope, Cormorant Garamond): fewer files.
        if sub == "latin" and fam in ARABIC_FAMILIES:
            continue
        style = re.search(r"font-style: (\w+)", body).group(1)
        weight = re.search(r"font-weight: ([\d ]+);", body).group(1)
        url = re.search(r"url\((https://[^)]+)\)", body).group(1)
        rng = ARABIC if sub == "arabic" else re.search(r"unicode-range: ([^;]+);", body).group(1)
        data = urllib.request.urlopen(url).read()
        key = (fam, style, sub, data)
        if key in seen:  # a variable font: Google serves the same file for every weight
            seen[key]["weights"].append(weight)
            continue
        name = f"{fam.lower().replace(' ', '-')}{'-italic' if style == 'italic' else ''}-{weight.replace(' ', '-')}-{sub}.woff2"
        path = OUT / name
        path.write_bytes(data)
        if sub == "arabic":
            opts = subset.Options()
            opts.flavor, opts.layout_features = "woff2", ["*"]
            font = subset.load_font(str(path), opts)
            sub_ = subset.Subsetter(opts)
            sub_.populate(unicodes=subset.parse_unicodes(ARABIC))
            sub_.subset(font)
            subset.save_font(font, str(path), opts)
        face = {"family": fam, "style": style, "weights": [weight], "file": name, "range": rng, "sub": sub}
        seen[key] = face
        faces.append(face)

    lines = ["/* Generated by scripts/build-fonts.py: self-hosted, subset fonts (SIL Open Font License). */"]
    metrics = {}
    for f in faces:
        ws = [int(x) for w in f["weights"] for x in w.split()]
        weight = f"{min(ws)} {max(ws)}" if len(set(ws)) > 1 else str(ws[0])
        if f["family"] not in metrics:
            metrics[f["family"]] = (TTFont(OUT / f["file"]), f["range"])
        lines.append(
            "@font-face {\n"
            f'  font-family: "{f["family"]}";\n  font-style: {f["style"]};\n  font-weight: {weight};\n'
            f'  font-display: swap;\n  src: url("./assets/fonts/{f["file"]}") format("woff2");\n'
            f"  unicode-range: {f['range']};\n}}"
        )
    for fam, (font, latin) in metrics.items():
        local, ref_path = FALLBACK[KIND[fam]]
        ref = TTFont(ref_path)
        # Latin widths say little about the Arabic a system font draws: only the vertical metrics are matched.
        size = 1.0 if fam in ARABIC_FAMILIES else avg_width(font) / avg_width(ref)
        upm, hhea = font["head"].unitsPerEm, font["hhea"]
        lines.append(
            "@font-face {\n"
            f'  font-family: "{fam} Fallback";\n  src: local("{local}"), local("{ref["name"].getDebugName(4)}");\n'
            f"  size-adjust: {size * 100:.2f}%;\n"
            f"  ascent-override: {hhea.ascent / upm / size * 100:.2f}%;\n"
            f"  descent-override: {abs(hhea.descent) / upm / size * 100:.2f}%;\n"
            f"  line-gap-override: {hhea.lineGap / upm / size * 100:.2f}%;\n"
            # Latin-only families: their stand-in mustn't draw the Arabic the next family in the stack draws.
            + ("" if fam in ARABIC_FAMILIES else f"  unicode-range: {latin};\n")
            + "}"
        )
    CSS.write_text("\n".join(lines) + "\n")
    print(f"{len(faces)} files, {sum((OUT / f['file']).stat().st_size for f in faces) // 1024} KB")


if __name__ == "__main__":
    main()
